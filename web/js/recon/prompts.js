// 视图通 · 拍照重建用到的提示词
export const VISION_PROMPT = `你是工程制图识图助手。图片是一道三视图题（第一角画法：主视图在左上，俯视图在主视图正下方，左视图在主视图正右方）。请把每个视图中的图线转录为坐标数据。
规则：
1. 每个视图用自己的局部坐标：原点在该视图外轮廓包围盒的左下角，u 向右，v 向上。三个视图必须用同一个比例（有尺寸数字就用 mm，没有就按图上格子或目测比例）。
2. 只转录轮廓线：粗实线 t="solid"，细虚线 t="dashed"，细点画线 t="center"。忽略尺寸线、尺寸数字、剖面线、文字、投影连线和 45° 辅助线。
3. 直线给两个端点；整圆给圆心和半径；圆弧给圆心、半径、起止角（度，逆时针，0° 为 u 正方向）。
4. 共线且相接的线段合并为一条；同一条线一段实一段虚时拆成两段。
5. 题目没有给出的视图（需要补画的），present 设为 false，其余字段留空。
6. 同一水平位置的线 v 值要一致，同一竖直位置的线 u 值要一致，数值保留到 0.5。
7. 先在心里把三个视图对照着读懂形体，再转录：同一个结构在各视图中的投影要符合长对正、高平齐、宽相等；被遮挡的结构画虚线。
8. 用 shape 字段一句话描述你读出的形体，features 列出主要结构（如“底板”“竖板”“通孔”“斜面”“前后贯通的槽”）。
9. 每个视图加 box 字段：该视图外轮廓在整张图片里的位置 [左, 上, 右, 下]，用相对图片宽、高的 0~1 比例（左上角为 0,0）。程序会按这个位置在照片里逐条精确量线，所以 box 要框住外轮廓、不要框进文字和尺寸。
只输出 JSON，不要任何解释：
{"unit":"mm","shape":"一句话描述形体","features":["结构1","结构2"],"views":{"front":{"present":true,"box":[0.05,0.08,0.45,0.42],"w":0,"h":0,"lines":[{"a":[0,0],"b":[0,0],"t":"solid"}],"circles":[{"c":[0,0],"r":0,"t":"solid"}],"arcs":[{"c":[0,0],"r":0,"from":0,"to":180,"t":"solid"}]},"top":{},"left":{}},"question":"题目文字，没有就留空","confidence":0.8}`;

export function alternativePrompt(base, found) {
  return `${base}\n\n【已经找到的解】\n${found.map((c, i) => `方案${i + 1}：${JSON.stringify({ ops: c.ops })}`).join('\n')}\n只给出了两个视图时，答案往往不唯一。请给出一个与上面所有方案都不同、但同样完全符合已知视图的形体（第三个视图会不同）。只输出 JSON。`;
}

// 识图自检：原图 + 按识别结果重绘的图，让视觉模型对照改错
export function selfCheckPrompt(json) {
  return `图1 是三视图题目的照片，图2 是根据你之前识别出的线条数据重新绘制的三视图（布局相同：主视图左上，俯视图在下，左视图在右；粗线为实线，细虚线为虚线）。
请逐个视图仔细对照两张图，检查：漏掉的线、多出的线、虚线和实线认错、线的位置或长度明显不对、漏掉或画错的圆和圆弧。
同时检查三个视图之间是否符合长对正、高平齐、宽相等。
然后输出修正后的完整 JSON（格式、坐标系与之前完全相同，包括 shape 和 features）。如果没有发现问题，原样输出。只输出 JSON。

之前的识别结果：
${JSON.stringify(json)}`;
}

// 照片核对：原图 + 重建形体反算出的三视图
export function verifyPrompt(given) {
  return `图1 是三视图题目的照片，图2 是根据重建的三维形体由程序反算出的三视图（布局相同；紫色是题目没有给出、由程序补画的视图）。
请只比较题目中已给出的视图（${given}）：图2 中对应视图的每一条线（位置、长短、实线或虚线）、每一个圆和圆弧是否与图1 一致。忽略尺寸标注、文字、比例和线宽的微小差别。
输出 JSON：{"consistent":true或false,"issues":["主视图：……","……"]}。issues 用具体位置描述，例如“主视图：右上方缺一个台阶，竖线应在约 2/3 宽处”“俯视图：中间两条竖线应为虚线”。只输出 JSON。`;
}

export function refineImagePrompt(base, issues, refs) {
  return `${base}

【对照照片发现的问题】
${issues.map(x => '- ' + x).join('\n') || '（无）'}
${refs ? `\n【联网检索到的相似题目资料，仅供参考，以照片为准】\n${refs}\n` : ''}
图1 是题目照片，图2 是当前方案反算出的三视图。请对照照片修改方案，使反算的三视图与照片一致。只输出 JSON。`;
}
