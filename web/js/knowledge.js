function bigrams(s) {
  const t = s.replace(/[\s，。、；：？！,.;:?!（）()“”"'《》·-]/g, '');
  const r = new Set();
  for (let i = 0; i < t.length - 1; i++) r.add(t.slice(i, i + 2));
  return r;
}

export function searchKB(query, k = 3) {
  const q = bigrams(query);
  const scored = KB.map(e => {
    let s = 0;
    for (const tag of e.tags) if (query.includes(tag)) s += 4 + tag.length;
    const tb = bigrams(e.title + e.tags.join(''));
    const bb = bigrams(e.body);
    for (const g of q) { if (tb.has(g)) s += 1.5; else if (bb.has(g)) s += 0.5; }
    return { e, s };
  }).filter(x => x.s > 1).sort((a, b) => b.s - a.s);
  return scored.slice(0, k).map(x => x.e);
}

